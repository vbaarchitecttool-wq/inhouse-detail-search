import { reflowSpecText } from "../text";

describe("reflowSpecText", () => {
  it("文の途中で折り返された改行を詰める", () => {
    const raw = "建築物等の新\n築及び増築に係る建築工事に適用する。";
    expect(reflowSpecText(raw)).toBe("建築物等の新築及び増築に係る建築工事に適用する。");
  });

  it("句点で終わる行の後の改行は残す", () => {
    const raw = "常温で行う。\n曲げ加工は、所定の形状とする。";
    expect(reflowSpecText(raw)).toBe(raw);
  });

  it("(1) ① 表 図 (注) などで始まる行の前の改行は残す", () => {
    const raw = [
      "(1) 受注者は、設計図書に従い、責任をもって履行するとともに、監督職員の指示に",
      "従う。",
      "(2) 受注者",
      "① 鉄筋の種類",
      "表5.3.5 かぶり厚さ",
      "図 1 断面",
      "(注) 単位はmm",
    ].join("\n");
    expect(reflowSpecText(raw).split("\n")).toEqual([
      "(1) 受注者は、設計図書に従い、責任をもって履行するとともに、監督職員の指示に従う。",
      "(2) 受注者",
      "① 鉄筋の種類",
      "表5.3.5 かぶり厚さ",
      "図 1 断面",
      "(注) 単位はmm",
    ]);
  });

  it("短い見出し行（例: (1) 適用範囲）の後ろの改行は残し、本文と連結しない", () => {
    // 1.1.1 の原文そのままの形
    const raw = [
      "(1) 適用範囲",
      "公共建築工事標準仕様書 (建築工事編)  (以下「標準仕様書」という。) は、建築物等の新",
      "築及び増築に係る建築工事に適用する。",
      "(3) 鋼管",
      "鋼管部分の材料は、特記による。",
    ].join("\n");
    expect(reflowSpecText(raw).split("\n")).toEqual([
      "(1) 適用範囲",
      "公共建築工事標準仕様書 (建築工事編)  (以下「標準仕様書」という。) は、建築物等の新築及び増築に係る建築工事に適用する。",
      "(3) 鋼管",
      "鋼管部分の材料は、特記による。",
    ]);
  });

  it("マーカー始まりでも長い行は折り返された本文として次行と連結する", () => {
    const raw = [
      "(ｴ) 「監督職員の指示」とは、監督職員が受注者等に対し、必要な事項を書面によって示すこ",
      "とをいう。",
    ].join("\n");
    expect(reflowSpecText(raw)).toBe(
      "(ｴ) 「監督職員の指示」とは、監督職員が受注者等に対し、必要な事項を書面によって示すことをいう。"
    );
  });

  it("表・図の見出しは長さによらず単独の行として残す", () => {
    const raw = ["表 5.5.1 ねじ節鉄筋継手の外観試験項目と合否判定基準", "外観試験項目 合格判定基準"].join("\n");
    expect(reflowSpecText(raw)).toBe(raw);
    const fig = ["図 5.3.2 直線定着の長さ及びフックありの定着の長さ", "L1h、L2h 又は L3h"].join("\n");
    expect(reflowSpecText(fig)).toBe(fig);
  });

  it("読点で終わる表題は折り返しとして次行と連結する", () => {
    const raw = [
      "表 18.8.1 コンクリート面、押出成形セメント板面、モルタル面、せっこうボード面、",
      "その他ボード面等のつや有合成樹脂エマルションペイント塗り",
      "工程 塗料",
    ].join("\n");
    expect(reflowSpecText(raw).split("\n")).toEqual([
      "表 18.8.1 コンクリート面、押出成形セメント板面、モルタル面、せっこうボード面、その他ボード面等のつや有合成樹脂エマルションペイント塗り",
      "工程 塗料",
    ]);
  });

  it("半角・全角が混在した括弧の項目記号もマーカーとして扱う", () => {
    const raw = ["(1) 外観試験で不合格となった溶接部の措置", "(ｱ）不合格となった溶接部を補修する。"].join("\n");
    expect(reflowSpecText(raw)).toBe(raw);
    expect(reflowSpecText("前の行\n（2）次の項目")).toBe("前の行\n（2）次の項目");
  });

  it("空行は前後ともそのまま残す", () => {
    expect(reflowSpecText("あ\n\nい")).toBe("あ\n\nい");
  });

  it("連結時に行末・行頭の空白を取り除く", () => {
    expect(reflowSpecText("鉄筋の \n　加工")).toBe("鉄筋の加工");
  });

  it("空文字・CRLF を扱える", () => {
    expect(reflowSpecText("")).toBe("");
    expect(reflowSpecText("あ\r\nい")).toBe("あい");
  });
});
