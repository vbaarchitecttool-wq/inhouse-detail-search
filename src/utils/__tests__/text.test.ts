import { reflowSpecText } from "../text";

describe("reflowSpecText", () => {
  it("文の途中で折り返された改行を詰める", () => {
    const raw = "建築物等の新\n築及び増築に係る建築工事に適用する。";
    expect(reflowSpecText(raw)).toBe("建築物等の新築及び増築に係る建築工事に適用する。");
  });

  it("句点で終わる行の後の改行は残す", () => {
    const raw = "常温で行う。\n曲げ加工は、所定の形状とする。";
    expect(reflowSpecText(raw)).toBe(raw);
  });

  it("(1) ① 表 図 (注) などで始まる行の前の改行は残す", () => {
    const raw = [
      "(1) 適用範囲",
      "本章は鉄筋工事に",
      "適用する。",
      "(2) 受注者",
      "① 鉄筋の種類",
      "表5.3.5 かぶり厚さ",
      "図 1 断面",
      "(注) 単位はmm",
    ].join("\n");
    expect(reflowSpecText(raw).split("\n")).toEqual([
      // 「(1) 適用範囲」は短いマーカー行＝見出しなので、後ろの改行も残す。
      // 本文行同士（「本文は鉄筋工事に」＋「適用する。」）は折り返しとして連結する
      "(1) 適用範囲",
      "本章は鉄筋工事に適用する。",
      "(2) 受注者",
      "① 鉄筋の種類",
      "表5.3.5 かぶり厚さ",
      "図 1 断面",
      "(注) 単位はmm",
    ]);
  });

  describe("見出し行（短いマーカー行）の後ろの改行", () => {
    it("見出し行の直後の本文行は連結しない（実データ 1.1.1 の例）", () => {
      const raw = [
        "(1) 適用範囲",
        "公共建築工事標準仕様書 (建築工事編)  (以下「標準仕様書」という。) は、建築物等の新",
        "築及び増築に係る建築工事に適用する。",
      ].join("\n");
      expect(reflowSpecText(raw).split("\n")).toEqual([
        "(1) 適用範囲",
        "公共建築工事標準仕様書 (建築工事編)  (以下「標準仕様書」という。) は、建築物等の新築及び増築に係る建築工事に適用する。",
      ]);
    });

    it("表・図の見出し（キャプション）の後ろの改行も残す", () => {
      const raw = "表 5.3.4 鉄筋の定着の長さ\n鉄筋の種類";
      expect(reflowSpecText(raw)).toBe(raw);
    });

    it("見出しの幅は半角を 0.5 文字として全角 20 文字まで", () => {
      // "(1) " = 全角 2 文字 + 全角 18 文字 = ちょうど 20 → 見出し
      const heading20 = "(1) 外観試験で不合格となった溶接部の措置";
      expect(reflowSpecText(`${heading20}\n不合格となった溶接部を補修する。`)).toBe(
        `${heading20}\n不合格となった溶接部を補修する。`
      );
      // 全角 21 文字 → 見出しではなく折り返しとして連結
      const line21 = "(1) 外観試験で不合格となった溶接部の措置等";
      expect(reflowSpecText(`${line21}\n不合格となった溶接部を補修する。`)).toBe(
        `${line21}不合格となった溶接部を補修する。`
      );
    });

    it("マーカーで始まる長い本文が文の途中で折り返された場合は従来どおり連結する", () => {
      const raw = [
        "(1) 受注者は、設計図書に定められた品質を確保するため、施工の各段階において必要な場合",
        "には、監督職員と協議する。",
      ].join("\n");
      expect(reflowSpecText(raw)).toBe(
        "(1) 受注者は、設計図書に定められた品質を確保するため、施工の各段階において必要な場合には、監督職員と協議する。"
      );
    });

    it("開き括弧・読点で終わる短いマーカー行は見出しではなく折り返しとして連結する", () => {
      // 連結時に次行の行頭空白は取り除かれる（従来どおり）
      expect(reflowSpecText("(4) １回の試験における圧縮強度の平均値(\n )は、6.9.1 式による。")).toBe(
        "(4) １回の試験における圧縮強度の平均値()は、6.9.1 式による。"
      );
      expect(reflowSpecText("(ｲ) 柱、梁、\n壁の順とする。")).toBe("(ｲ) 柱、梁、壁の順とする。");
    });

    it("次の行が傍点の抽出残り（・・）で始まる場合は見出し扱いせず連結する", () => {
      const raw = ["(c) こて", "・・", "塗りの場合、所定のこて", "・・", "を用いる。"].join("\n");
      expect(reflowSpecText(raw)).toBe("(c) こて・・塗りの場合、所定のこて・・を用いる。");
    });

    it("見出し行の次がマーカー行・句点終わりの行でも従来どおり改行を残す", () => {
      const raw = ["(3) 標準仕様書の適用", "(ｱ) ２章以降の各章は、１章と併せて適用する。", "(4) 優先順位"].join("\n");
      expect(reflowSpecText(raw)).toBe(raw);
    });
  });

  it("空行は構造として残す（空行の次の行を空行に連結しない）", () => {
    expect(reflowSpecText("あ\n\nい")).toBe("あ\n\nい");
    expect(reflowSpecText("あ。\n\nい")).toBe("あ。\n\nい");
  });

  it("連結時に行末・行頭の空白を取り除く", () => {
    expect(reflowSpecText("鉄筋の \n　加工")).toBe("鉄筋の加工");
  });

  it("空文字・CRLF を扱える", () => {
    expect(reflowSpecText("")).toBe("");
    expect(reflowSpecText("あ\r\nい")).toBe("あい");
  });
});
