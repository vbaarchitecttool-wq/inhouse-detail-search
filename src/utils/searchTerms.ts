// 検索語の「表記ゆれ・現場用語」の読み替え表。
//
// 方針（重要）:
//   - 載せてよいのは「同じ物・同じ行為を指す別の書き方」だけ。
//     例）石膏ボード＝せっこうボード（仕様書の表記）、コーキング＝シーリング。
//   - 仕様・性能が違うものを同じ語として扱わない。
//     特に 区画壁（耐火・防火の認定／告示仕様）と一般の間仕切壁は、どちらも
//     ボード2重張りでも別仕様。耐火・防火・不燃・区画・間仕切 に関わる語は
//     この表に絶対に載せない（searchTerms.test.ts で機械的に検査している）。
//   - 読み替え先は必ず仕様書の原文に出てくる語にする（同テストで検査）。
//
// 送り仮名の違い（取付け／取り付け、締固め／締め固め）は表ではなく
// search.ts の「送り仮名ゆるめ照合」で自動的に吸収する。

